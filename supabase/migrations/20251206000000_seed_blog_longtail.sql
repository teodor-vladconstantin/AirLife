## Cât consumă pe oră?

La pornire, când aparatul duce camera la temperatura setată, consumul este mai mare, în jur de 1 kWh/oră sau puțin peste. După ce temperatura este atinsă, compresorul inverter își reduce turația și consumul coboară de regulă spre **0,5–0,8 kWh/oră**. Un exemplu măsurat de un utilizator, la un model de 12000 BTU, arată circa 850 W la pornire și 450–600 W după stabilizare.

Aceste cifre sunt orientative: ghidurile publice nu dau valori identice, iar consumul real depinde de temperatura de afară, izolația locuinței și setări.

## Formula pentru costul pe factură

Costul = consum (kWh) × ore de funcționare × prețul kWh din factura ta.

Exemplu de calcul: dacă aparatul consumă în medie 0,7 kWh/oră și rulează 8 ore pe zi, consumul zilnic este 5,6 kWh. Înmulțești cu prețul kWh de pe factura ta și cu numărul de zile.

